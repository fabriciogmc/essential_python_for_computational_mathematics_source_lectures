# Examples of structured data types:
# Dictionaries and lists


my_personal_data = {"name": "Fabricio", "profession": "scientist"}
my_books = ["math for computer science", "data structures and algorithms"]

print("My name is: ", my_personal_data["name"])
print("My second book is: ", my_books[1])

print(my_personal_data.keys()) # Here we access an operation
print(my_personal_data["name"]) # Here we access an attribute

